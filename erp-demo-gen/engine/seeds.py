"""Load, validate, and complete the LLM-authored seeds.json.

The LLM provides the qualitative dimension data. This module guarantees the
engine has *enough* of everything: it extends the customer/vendor name pools to
the required counts (via names.py), supplies default departments, and fails
loudly only when something genuinely creative is missing (e.g. no products).
"""
from __future__ import annotations

import json

from . import names
from .util import Rng

DEFAULT_DEPARTMENTS = [
    "Sales", "Procurement", "Operations", "Finance", "Human Resources",
    "Warehouse", "Production", "Quality", "IT", "Logistics",
]

# How many distinct company names we ask the LLM to provide before Python
# synthesizes the rest. Keeps the LLM call small while still seeding flavour.
CUSTOMER_NAME_CAP = 60
VENDOR_NAME_CAP = 30


def load_seeds(path: str) -> dict:
    with open(path) as f:
        return json.load(f)


def template(profile, needs_raw: bool, needs_work_centers: bool) -> dict:
    """A skeleton + counts the LLM should fill, written next to spec.json."""
    n_products = profile.n_products
    tpl = {
        "_instructions": (
            "Fill this file with realistic, on-industry names for a fictional "
            f"{profile.industry} company called '{profile.company_name}'. "
            "Numbers/dates/transactions are generated by the engine — you only "
            "provide names, categories, and cost/price ranges. Provide AT LEAST "
            "the counts noted in each *_target field; more is fine."
        ),
        "company": {
            "name": profile.company_name,
            "tagline": "<short brand tagline>",
            "hq_city": "<US city>",
            "domain": f"{profile.slug.replace('_','')}.com",
        },
        "products_target": min(n_products, 200),
        "products": [
            {"name": "<product name>", "category": "<category>", "uom": "ea",
             "unit_cost_min": 1.0, "unit_cost_max": 5.0, "margin_pct": 35}
        ],
        "customer_names_target": min(profile.n_customers, CUSTOMER_NAME_CAP),
        "customer_names": ["<customer company name>"],
        "vendor_names_target": min(profile.n_vendors, VENDOR_NAME_CAP),
        "vendor_names": ["<vendor company name>"],
        "departments": DEFAULT_DEPARTMENTS,
    }
    if needs_raw:
        tpl["raw_materials_target"] = 30
        tpl["raw_materials"] = [
            {"name": "<raw material>", "category": "<category>", "uom": "kg", "unit_cost": 2.5}
        ]
    if needs_work_centers:
        tpl["work_centers_target"] = profile.n_work_centers
        tpl["work_centers"] = [
            {"name": "<work center / line>", "capacity_per_hour": 120, "cost_per_hour": 85}
        ]
    return tpl


# Sections an industry may add that the engine passes straight through to its
# generator (machines, accessories, chart of accounts, expense catalogue, ...).
PASSTHROUGH = [
    "machines", "accessories", "warehouses", "vendors", "customers", "carriers",
    "chart_of_accounts", "expense_categories", "fixed_assets", "notes",
    # talaşlı imalat (contract_machining) bölümleri
    "shop_machines", "operations", "defect_codes", "downtime_reasons",
    "subcontract_processes", "customer_programs", "maintenance_types",
    "tooling", "quality_characteristics", "hse_types", "packaging",
    "routing_templates", "product_families",
]


def validate_and_fill(seeds: dict, profile, rng: Rng, needs_raw: bool, needs_work_centers: bool,
                      name_style: str = "us") -> dict:
    out = {}
    for key in PASSTHROUGH:
        if key in seeds:
            out[key] = seeds[key]

    company = dict(seeds.get("company") or {})
    company.setdefault("name", profile.company_name)
    company.setdefault("tagline", "")
    company.setdefault("hq_city", "New York")
    company.setdefault("domain", names.slug_domain(profile.company_name))
    out["company"] = company

    products = [p for p in seeds.get("products", []) if _real(p.get("name"))]
    if not products and not (out.get("machines") or out.get("accessories")):
        raise SystemExit(
            "seeds.json must contain a non-empty 'products' list "
            "(or 'machines'/'accessories' for industries that split the catalogue).")
    out["products"] = products

    if needs_raw:
        raws = [r for r in seeds.get("raw_materials", []) if _real(r.get("name"))]
        if not raws:
            # Derive plausible raw materials from product categories as a fallback.
            cats = list({p.get("category", "Material") for p in products})
            raws = [{"name": f"{c} Stock", "category": c, "uom": "kg",
                     "unit_cost": round(rng.lognormal(2.5, 0.4), 2)} for c in cats]
        out["raw_materials"] = raws

    if needs_work_centers:
        wcs = [w for w in seeds.get("work_centers", []) if _real(w.get("name"))]
        if not wcs:
            wcs = [{"name": f"Line {i+1}", "capacity_per_hour": 100, "cost_per_hour": 80}
                   for i in range(profile.n_work_centers)]
        out["work_centers"] = wcs

    # departments may be plain names or {name, cost_center, roles:[...]} objects
    depts = [d for d in seeds.get("departments", [])
             if _real(d.get("name") if isinstance(d, dict) else d)] or DEFAULT_DEPARTMENTS
    out["departments"] = depts

    # the long tail of company names is synthesized in the right regional style
    if name_style == "eu_tr":
        from .locales import extend_company_names_intl as extend
    elif name_style == "tr":
        from .locales import extend_company_names_tr as extend
    else:
        extend = names.extend_company_names

    cust_seed = [c for c in seeds.get("customer_names", []) if _real(c)]
    out["customer_names"] = extend(rng.stream("cust_names"), cust_seed, profile.n_customers)

    vend_seed = [v for v in seeds.get("vendor_names", []) if _real(v)]
    out["vendor_names"] = extend(rng.stream("vend_names"), vend_seed, profile.n_vendors)

    return out


def _real(v) -> bool:
    """Reject placeholder strings like '<product name>'."""
    if not isinstance(v, str):
        return bool(v)
    v = v.strip()
    return bool(v) and not (v.startswith("<") and v.endswith(">"))
